#[test]
fn test_stub_commands_return_not_implemented() {
    for cmd in LEGACY_STUB_COMMANDS {
        let output = Command::new(env!("CARGO_BIN_EXE_xtask"))
            .arg(cmd)
            .output()
            .expect("failed to execute xtask");

        assert_eq!(
            output.status.code(),
            Some(2),
            "Command '{}' should return exit code 2",
            cmd
        );
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert!(
            stderr.contains(&format!("NOT IMPLEMENTED: {}", cmd)),
            "Command '{}' stderr should contain 'NOT IMPLEMENTED: {}', got: {}",
            cmd,
            cmd,
            stderr
        );
    }
}
