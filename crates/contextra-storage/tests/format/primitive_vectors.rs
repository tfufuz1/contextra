#[test]
fn xxh64_laengenvektoren_stimmen_mit_referenz() {
    for &(n, seed, expected) in XXH64_LEN_VECTORS {
        assert_eq!(
            xxh64(&data(n), seed),
            expected,
            "XXH64 len={n} seed=0x{seed:016x}"
        );
    }
}

#[test]
fn crc32c_laengenvektoren_stimmen_mit_referenz() {
    for &(n, seed, expected) in CRC32C_LEN_VECTORS {
        let seed = u32::try_from(seed).unwrap_or(0);
        assert_eq!(
            crc32c(seed, &data(n)),
            expected,
            "CRC32C len={n} seed=0x{seed:08x}"
        );
    }
}

#[test]
fn crc32c_fortsetzung_ist_teilbar() {
    // crc32c(seed, a‖b) == crc32c(crc32c(seed, a), b): Fortsetzung über Teilstücke (SPEC §4).
    let all = data(70);
    let (a, b) = all.split_at(33);
    assert_eq!(crc32c(0, &all), crc32c(crc32c(0, a), b));
}
