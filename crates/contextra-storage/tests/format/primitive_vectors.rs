//! # Primitiv-Vektoren für XXH64 und CRC-32C über alle Längenzweige
//!
//! Die Werte stammen aus einer **unabhängigen Referenz** (PyPI `xxhash` 4.1.0 und
//! `crc32c` 2.9.post0), nicht aus dem Kern und nicht aus `goldens_plain.json`.
//! Sie decken die Blockpfade (ab 32 Byte bei XXH64) und alle Tail-Zweige (1–31 Byte)
//! ab, die Anhang A.1 mit drei Werten nicht erreicht.
//! Eingabe: `data(n)[i] = (7·i + 3) mod 256`.

use contextra_storage::codec::crc32c::crc32c;
use contextra_storage::codec::xxh64::xxh64;

fn data(n: usize) -> Vec<u8> {
    (0..n)
        .map(|i| u8::try_from((7 * i + 3) % 256).unwrap_or(0))
        .collect()
}

