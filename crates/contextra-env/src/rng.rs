//! Random number generator port trait and deterministic SplitMix64 implementation.

use std::collections::hash_map::RandomState;
use std::hash::{BuildHasher, Hasher};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;

// =========================================================================
// SECTION: Module Constants
// ANCHOR[id=rng-constants,epic=rng,seq=1]
// NOTE: SplitMix64 verwendet den Goldenen Schnitt für 64-Bit-Ganzzahlen.
// Bewusst KEIN globaler Zähler (docs/crates/contextra-env.md §1, Punkt 5).
// =========================================================================

/// Fractional approximation of the golden ratio: $2^{64} / \phi \approx \text{0x9e3779b97f4a7c15}$.
/// Wird in SplitMix64 als Schrittweite (Weyl sequence increment) genutzt.
const GOLDEN_RATIO_64: u64 = 0x9e37_79b9_7f4a_7c15;

/// Extrahiert die oberen 32 Bit eines 64-Bit-Werts.
///
/// Der Wert ist nach dem Shift strikt kleiner als 2^32; die Konvertierung ist daher exakt.
#[inline]
#[allow(clippy::cast_possible_truncation)]
fn high_u32(value: u64) -> u32 {
    (value >> 32) as u32
}

// !SECTION: Module Constants

