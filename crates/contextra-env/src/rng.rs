#[cfg(test)]
mod tests {
    use super::*;

    /// Statische Typprüfung, ob `&dyn Rng` dynamisch dispatchbar ist (Object Safety).
    fn _assert_dyn_rng(_: Option<&dyn Rng>) {}

    #[test]
    fn test_seeded_rng_reproducibility() {
        // NOTE: Verifiziert INV-ENV-RNG-1 (Gleicher Seed liefert identische Zahlenfolge)
        let rng1 = SeededRng::new(12345);
        let rng2 = SeededRng::new(12345);

        for _ in 0..10 {
            assert_eq!(rng1.next_u64(), rng2.next_u64());
        }
    }

    #[test]
    fn test_from_entropy_different_sequences() {
        // NOTE: Verifiziert, dass zwei Aufrufe von `from_entropy()` divergente Sequenzen erzeugen
        let rng1 = SeededRng::from_entropy();
        let rng2 = SeededRng::from_entropy();

        let draws1: Vec<u64> = (0..4).map(|_| rng1.next_u64()).collect();
        let draws2: Vec<u64> = (0..4).map(|_| rng2.next_u64()).collect();

        assert_ne!(
            draws1, draws2,
            "from_entropy instances generated identical 4-draw sequences"
        );
    }

    #[test]
    fn test_seeded_rng_different_seeds() {
        let rng1 = SeededRng::new(100);
        let rng2 = SeededRng::new(200);

        assert_ne!(rng1.next_u64(), rng2.next_u64());
    }

    #[test]
    fn test_next_unit_f64_in_bounds() {
        // NOTE: Verifiziert INV-ENV-RNG-2 (Intervall-Grenzen 0.0 <= val < 1.0)
        let rng = SeededRng::new(42);
        for _ in 0..1000 {
            let val = rng.next_unit_f64();
            assert!((0.0..1.0).contains(&val), "Value out of bounds: {val}");
        }
    }

    #[test]
    fn test_fill_bytes_lengths() {
        let rng = SeededRng::new(999);

        for len in [0, 1, 7, 8, 9] {
            let mut buf = vec![0u8; len];
            rng.fill_bytes(&mut buf);
            assert_eq!(buf.len(), len);
        }
    }

    #[test]
    fn test_arc_dyn_rng() {
        let rng: Arc<dyn Rng> = Arc::new(SeededRng::new(777));
        _assert_dyn_rng(Some(rng.as_ref()));

        let mut buf = [0u8; 4];
        rng.fill_bytes(&mut buf);
        let f = rng.next_unit_f64();
        assert!((0.0..1.0).contains(&f));
    }
}

// !SECTION: Unit Tests
