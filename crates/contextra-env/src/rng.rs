#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    /// Statische Typprüfung, ob `&dyn Rng` dynamisch dispatchbar ist (Object Safety).
    fn _assert_dyn_rng(_: Option<&dyn Rng>) {}

    #[test]
    fn test_seeded_rng_reproducibility() {
        // NOTE: Verifiziert INV-ENV-RNG-1 (Gleicher Seed liefert identische Zahlenfolge)
        let rng1 = SeededRng::new(12345);
        let rng2 = SeededRng::new(12345);

        for _ in 0..10 {
            assert_eq!(rng1.next_u64(), rng2.next_u64());
        }
    }

    #[test]
    fn test_from_entropy_different_sequences() {
        // NOTE: Verifiziert, dass zwei Aufrufe von `from_entropy()` divergente Sequenzen erzeugen
        let rng1 = SeededRng::from_entropy();
        let rng2 = SeededRng::from_entropy();

        let draws1: Vec<u64> = (0..4).map(|_| rng1.next_u64()).collect();
        let draws2: Vec<u64> = (0..4).map(|_| rng2.next_u64()).collect();

        assert_ne!(
            draws1, draws2,
            "from_entropy instances generated identical 4-draw sequences"
        );
    }

    #[test]
    fn test_seeded_rng_different_seeds() {
        let rng1 = SeededRng::new(100);
        let rng2 = SeededRng::new(200);

        assert_ne!(rng1.next_u64(), rng2.next_u64());
    }

    #[test]
    fn test_next_unit_f64_in_bounds() {
        // NOTE: Verifiziert INV-ENV-RNG-2 (Intervall-Grenzen 0.0 <= val < 1.0)
        let rng = SeededRng::new(42);
        for _ in 0..1000 {
            let val = rng.next_unit_f64();
            assert!((0.0..1.0).contains(&val), "Value out of bounds: {val}");
        }
    }

    #[test]
    fn test_next_u32_is_high_half_of_next_u64() {
        // NOTE: Spec §2.2 — next_u32 liefert die oberen 32 Bit derselben Ziehung.
        let by_u64 = SeededRng::new(7);
        let by_u32 = SeededRng::new(7);
        for _ in 0..256 {
            assert_eq!(by_u32.next_u32(), high_u32(by_u64.next_u64()));
        }
    }

    #[test]
    fn test_fill_bytes_lengths() {
        let rng = SeededRng::new(999);

        for len in [0, 1, 7, 8, 9, 16, 17] {
            let mut buf = vec![0u8; len];
            rng.fill_bytes(&mut buf);
            assert_eq!(buf.len(), len);
        }
    }

    #[test]
    fn test_fill_bytes_is_little_endian_stream_of_next_u64() {
        // NOTE: Der Byte-Strom ist die LE-Aneinanderreihung der 64-Bit-Ziehungen,
        // der Restblock nutzt die niederwertigen Bytes der letzten Ziehung.
        for len in 0..=17usize {
            let by_bytes = SeededRng::new(31337);
            let by_words = SeededRng::new(31337);

            let mut buf = vec![0u8; len];
            by_bytes.fill_bytes(&mut buf);

            let mut expected = Vec::with_capacity(len + 8);
            while expected.len() < len {
                expected.extend_from_slice(&by_words.next_u64().to_le_bytes());
            }
            expected.truncate(len);

            assert_eq!(buf, expected, "fill_bytes stream mismatch at len={len}");
        }
    }

    #[test]
    fn test_seeded_rng_concurrent_draws_are_unique() {
        // NOTE: Verifiziert lock-freie Nebenläufigkeit: 8 Threads × 1000 Ziehungen,
        // alle 8000 Werte müssen paarweise verschieden sein (Bijektivität der Mischung).
        let rng = Arc::new(SeededRng::new(5));
        let handles: Vec<_> = (0..8)
            .map(|_| {
                let r = rng.clone();
                std::thread::spawn(move || (0..1000).map(|_| r.next_u64()).collect::<Vec<_>>())
            })
            .collect();

        let mut all = BTreeSet::new();
        for handle in handles {
            for value in handle.join().unwrap_or_default() {
                assert!(all.insert(value), "duplicate RNG output {value}");
            }
        }
        assert_eq!(all.len(), 8000);
    }

    #[test]
    fn test_arc_dyn_rng() {
        let rng: Arc<dyn Rng> = Arc::new(SeededRng::new(777));
        _assert_dyn_rng(Some(rng.as_ref()));

        let mut buf = [0u8; 4];
        rng.fill_bytes(&mut buf);
        let f = rng.next_unit_f64();
        assert!((0.0..1.0).contains(&f));
        let _ = rng.next_u32();
    }
}

