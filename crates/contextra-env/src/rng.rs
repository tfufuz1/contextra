/// A fast, deterministic 64-bit pseudorandom number generator using SplitMix64
/// with atomic state transitions (`AtomicU64`).
///
/// Lock-free and thread-safe without requiring `Mutex`.
///
/// # Entropy Seeding
/// Note that non-deterministic entropy seeding (e.g., via `OsRng` or system entropy)
/// is the responsibility of the Composition Root. Application entry points should gather entropy
/// at startup and pass the initial seed to [`SeededRng::new`].
#[derive(Debug)]
pub struct SeededRng {
    /// Interner 64-Bit-Zustand, atomar fortgeschaltet über `fetch_add(GOLDEN_RATIO_64)`.
    state: AtomicU64,
}

impl SeededRng {
    /// Creates a new [`SeededRng`] initialized with the given seed.
    ///
    /// Garantiert exakte Bitgleichheit zu den kanonischen Golden-Testvektoren.
    pub const fn new(seed: u64) -> Self {
        Self {
            state: AtomicU64::new(seed),
        }
    }

    /// Creates a new [`SeededRng`] seeded from process/runtime entropy.
    ///
    /// # Non-Cryptographic Usage
    /// This entropy source uses [`std::collections::hash_map::RandomState`], whose keys are
    /// randomized per instance by the standard library. It is intended strictly for
    /// non-cryptographic usages such as jitter, load balancing, and randomized algorithm
    /// initialization. Cryptographic keys and salts MUST use dedicated cryptographic RNGs.
    ///
    /// # Composition Root Architecture
    /// Only Composition Roots (application entry points) should construct a [`SeededRng`] via `from_entropy`.
    /// Internal library logic MUST accept an injected [`Rng`] instance instead of calling `from_entropy` directly.
    pub fn from_entropy() -> Self {
        // NOTE: Zwei unabhängig gekeyte Hasher; jeder RandomState::new() erhält frische Schlüssel.
        let h1 = {
            let mut hasher = RandomState::new().build_hasher();
            hasher.write_u64(GOLDEN_RATIO_64);
            hasher.finish()
        };
        let h2 = {
            let mut hasher = RandomState::new().build_hasher();
            hasher.write_u64(h1);
            hasher.finish()
        };
        Self::new(h1 ^ h2.rotate_left(32))
    }
}

impl Rng for SeededRng {
    /// Generiert die nächste 64-Bit-Pseudozufallszahl gemäß SplitMix64.
    ///
    /// # Didaktische Erklärung der Bit-Operationen:
    /// 1. `fetch_add`: Atomares Inkrementieren des Zustands um den Goldenen Schnitt.
    ///    Der Rückgabewert ist der Zustand *vor* dem Inkrement.
    /// 2. `wrapping_add`: Zustandswert für diese Ziehung isolieren (neuer Zustand).
    /// 3. Bit-Mixing-Konstanten `0xbf58476d1ce4e5b9` und `0x94d049bb133111eb`:
    ///    Verteilen die Entropie gleichmäßig über alle 64 Bits (Avalanche-Effekt).
    ///
    /// Da die Mischfunktion bijektiv ist und der Zustand über 2^64 Schritte verschieden bleibt,
    /// sind alle Ausgaben eines Generators innerhalb einer Periode paarweise verschieden.
    fn next_u64(&self) -> u64 {
        let mut z = self
            .state
            .fetch_add(GOLDEN_RATIO_64, Ordering::SeqCst)
            .wrapping_add(GOLDEN_RATIO_64);
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    /// Befüllt den Zielpuffer blockweise mit Little-Endian 64-Bit Werten.
    fn fill_bytes(&self, mut dest: &mut [u8]) {
        while !dest.is_empty() {
            let bytes = self.next_u64().to_le_bytes();
            let len = dest.len().min(bytes.len());
            if let (Some(dst_chunk), Some(src_chunk)) = (dest.get_mut(..len), bytes.get(..len)) {
                dst_chunk.copy_from_slice(src_chunk);
            }
            match dest.get_mut(len..) {
                Some(rest) => dest = rest,
                None => break,
            }
        }
    }

    /// Skaliert eine Zufallszahl in das halboffene Fließkommaintervall `[0.0, 1.0)`.
    ///
    /// # Didaktische Erklärung:
    /// Ein IEEE-754 `f64` besitzt eine 53-Bit Mantisse. Durch `>> 11` werden exakt
    /// 53 Bits Zufall extrahiert und durch Division durch $2^{53}$ normalisiert.
    fn next_unit_f64(&self) -> f64 {
        let mantissa = self.next_u64() >> 11;
        (mantissa as f64) * (1.0 / (1u64 << 53) as f64)
    }
}

// !SECTION: SeededRng (SplitMix64) Implementation

// =========================================================================
// SECTION: Blanket Implementation for Arc<T>
// ANCHOR[id=rng-arc,epic=rng,seq=4]
// NOTE: Erlaubt direkte Nutzung von `Arc<dyn Rng>` ohne zusätzliche Allokationen.
// =========================================================================

impl<T: Rng + ?Sized> Rng for Arc<T> {
    #[inline]
    fn next_u64(&self) -> u64 {
        (**self).next_u64()
    }

    #[inline]
    fn next_u32(&self) -> u32 {
        (**self).next_u32()
    }

    #[inline]
    fn fill_bytes(&self, dest: &mut [u8]) {
        (**self).fill_bytes(dest);
    }

    #[inline]
    fn next_unit_f64(&self) -> f64 {
        (**self).next_unit_f64()
    }
}

