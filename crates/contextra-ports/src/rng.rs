//! Random number generator port traits with strict type-level separation.
//!
//! # Architecture Role
//! To ensure deterministic testing and prevent non-cryptographic or test PRNGs from being used
//! in security-sensitive cryptographic paths, RNG capabilities are split into two distinct traits:
//!
//! - [`EntropyRng`]: For cryptographic keys, nonces, and salts. Backed by OS or KMS entropy.
//! - [`SeededRng`]: For deterministic non-cryptographic simulation, jitter, and tests.
//!
//! [`SeededRng`] does NOT implement [`EntropyRng`]. Functions accepting cryptographic entropy
//! enforcing [`EntropyRng`] will reject test/seeded RNGs at compile time.

use std::sync::Arc;

// TODO(WP-S1 / PR-3 Schritt 1): `CryptoRng` Marker-Trait implementieren.
// Aktuell implementiert `SystemRng` hier fälschlicherweise `EntropyRng` via std RandomState/Hasher,
// was KEIN kryptographischer Zufallszahlengenerator (CSPRNG) ist und zu Befund F-01 führte.
// Implementierungsaufgabe:
// 1. Definiere `pub trait CryptoRng: Send + Sync {}` als typ-sicheren Marker für echte CSPRNGs.
// 2. `SystemRng` darf `CryptoRng` NICHT implementieren.
// 3. Kryptographische Pfade (wie Ed25519-Schlüsselerzeugung) müssen statisch `CryptoRng` fordern.
/// Standard non-cryptographic system entropy generator backed by system/process entropy.
#[derive(Debug, Default, Clone, Copy)]
pub struct SystemRng;

impl SystemRng {
    /// Creates a new [`SystemRng`].
    pub fn new() -> Self {
        Self
    }

    /// Generates the next pseudorandom 64-bit unsigned integer.
    pub fn next_u64(&self) -> u64 {
        SeededRng::next_u64(self)
    }

    /// Fills `dest` with pseudorandom bytes.
    pub fn fill_bytes(&self, dest: &mut [u8]) {
        SeededRng::fill_bytes(self, dest);
    }

    /// Returns a pseudorandom `f64` in `[0.0, 1.0)`.
    pub fn next_unit_f64(&self) -> f64 {
        SeededRng::next_unit_f64(self)
    }
}

impl SeededRng for SystemRng {
    fn next_u64(&self) -> u64 {
        use std::collections::hash_map::RandomState;
        use std::hash::{BuildHasher, Hasher};
        RandomState::new().build_hasher().finish()
    }

    fn fill_bytes(&self, dest: &mut [u8]) {
        let mut written = 0;
        while written < dest.len() {
            let val = self.next_u64();
            let bytes = val.to_le_bytes();
            let chunk = (dest.len() - written).min(8);
            dest[written..written + chunk].copy_from_slice(&bytes[..chunk]);
            written += chunk;
        }
    }

    fn next_unit_f64(&self) -> f64 {
        let mantissa = self.next_u64() >> 11;
        (mantissa as f64) * (1.0 / (1u64 << 53) as f64)
    }
}

/// Marker trait for cryptographically secure random number generators (CSPRNGs).
pub trait CryptoRng: Send + Sync + 'static {}

/// DEPRECATION NOTICE: This implementation of [`EntropyRng`] for [`SystemRng`] uses non-CSPRNG
/// process entropy (`std::collections::hash_map::RandomState`) and WILL BE REMOVED in Session W3-01.
///
/// Migration path: Use `OsEntropyRng` for cryptographic material generation.
impl EntropyRng for SystemRng {
    fn fill_bytes(&self, dest: &mut [u8]) {
        SeededRng::fill_bytes(self, dest);
    }

    fn next_u64(&self) -> u64 {
        SeededRng::next_u64(self)
    }
}

/// Port trait for cryptographic entropy sources (keys, nonces, IVs, salts).
///
/// MUST be backed by genuine system/OS entropy or KMS. Test PRNGs MUST NOT implement this trait.
pub trait EntropyRng: Send + Sync + 'static {
    /// Fills `dest` with cryptographically secure random bytes.
    fn fill_bytes(&self, dest: &mut [u8]);

    /// Generates the next pseudorandom 64-bit unsigned integer from secure entropy.
    fn next_u64(&self) -> u64;
}

/// Port trait for non-cryptographic, deterministic, or test random number generators.
///
/// Used for simulations, load-balancing jitter, randomized algorithm testing, and test fixtures.
/// MUST NOT be used for cryptographic key or nonce generation.
pub trait SeededRng: Send + Sync + 'static {
    /// Generates the next pseudorandom 64-bit unsigned integer.
    fn next_u64(&self) -> u64;

    /// Fills `dest` with pseudorandom bytes generated by this RNG.
    fn fill_bytes(&self, dest: &mut [u8]);

    /// Returns a pseudorandom `f64` value in the half-open interval `[0.0, 1.0)`.
    fn next_unit_f64(&self) -> f64;
}

/// Alias for [`SeededRng`] trait for specification and backward naming compatibility.
///
/// Deprecated per E55 / §7.4: `Rng` is ambiguous. Use [`EntropyRng`] or [`SeededRng`] explicitly.
#[deprecated(since = "0.1.0", note = "Use SeededRng or EntropyRng per §7.4 / E55")]
pub use SeededRng as Rng;

impl<T: EntropyRng + ?Sized> EntropyRng for Arc<T> {
    fn fill_bytes(&self, dest: &mut [u8]) {
        (**self).fill_bytes(dest);
    }

    fn next_u64(&self) -> u64 {
        (**self).next_u64()
    }
}

impl<T: SeededRng + ?Sized> SeededRng for Arc<T> {
    fn next_u64(&self) -> u64 {
        (**self).next_u64()
    }

    fn fill_bytes(&self, dest: &mut [u8]) {
        (**self).fill_bytes(dest);
    }

    fn next_unit_f64(&self) -> f64 {
        (**self).next_unit_f64()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct MockEntropyRng;
    impl EntropyRng for MockEntropyRng {
        fn fill_bytes(&self, dest: &mut [u8]) {
            dest.fill(0xAA);
        }
        fn next_u64(&self) -> u64 {
            0x1234_5678_9ABC_DEF0
        }
    }

    struct MockSeededRng;
    impl SeededRng for MockSeededRng {
        fn next_u64(&self) -> u64 {
            42
        }
        fn fill_bytes(&self, dest: &mut [u8]) {
            dest.fill(0x55);
        }
        fn next_unit_f64(&self) -> f64 {
            0.5
        }
    }

    fn assert_dyn_entropy(_: Option<&dyn EntropyRng>) {}
    fn assert_dyn_seeded(_: Option<&dyn SeededRng>) {}

    #[test]
    fn test_rng_object_safety_and_type_separation() {
        let entropy_rng = Arc::new(MockEntropyRng);
        let seeded_rng = Arc::new(MockSeededRng);

        assert_dyn_entropy(Some(entropy_rng.as_ref()));
        assert_dyn_seeded(Some(seeded_rng.as_ref()));

        let dyn_entropy: Arc<dyn EntropyRng> = entropy_rng;
        let mut buf = [0u8; 4];
        dyn_entropy.fill_bytes(&mut buf);
        assert_eq!(buf, [0xAA; 4]);
        assert_eq!(dyn_entropy.next_u64(), 0x1234_5678_9ABC_DEF0);

        let dyn_seeded: Arc<dyn SeededRng> = seeded_rng;
        assert_eq!(dyn_seeded.next_u64(), 42);
        assert_eq!(dyn_seeded.next_unit_f64(), 0.5);
    }

    // Compilation test helper verifying key generation function accepts ONLY EntropyRng
    fn generate_key<R: EntropyRng>(rng: &R, out: &mut [u8; 32]) {
        rng.fill_bytes(out);
    }

    #[test]
    fn test_entropy_rng_accepted_for_keys() {
        let rng = MockEntropyRng;
        let mut key = [0u8; 32];
        generate_key(&rng, &mut key);
        assert_eq!(key, [0xAA; 32]);
    }
}
