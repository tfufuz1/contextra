//! Random number generator port traits and deterministic SplitMix64 implementation.

use std::collections::hash_map::RandomState;
use std::hash::{BuildHasher, Hasher};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;

static ENTROPY_COUNTER: AtomicU64 = AtomicU64::new(1);

/// Port trait for cryptographic entropy sources (keys, nonces, IVs, salts).
///
/// MUST be backed by genuine system/OS entropy or KMS. Test PRNGs MUST NOT implement this trait.
pub trait EntropyRng: Send + Sync + 'static {
    /// Fills `dest` with cryptographically secure random bytes.
    fn fill_bytes(&self, dest: &mut [u8]);

    /// Generates the next pseudorandom 64-bit unsigned integer from secure entropy.
    fn next_u64(&self) -> u64;
}

/// Port trait for non-cryptographic, deterministic, or test random number generators.
///
/// Used for simulations, load-balancing jitter, randomized algorithm testing, and test fixtures.
/// MUST NOT be used for cryptographic key or nonce generation.
pub trait Rng: Send + Sync + 'static {
    /// Generates the next pseudorandom 64-bit unsigned integer.
    fn next_u64(&self) -> u64;

    /// Fills `dest` with pseudorandom bytes generated by this RNG.
    fn fill_bytes(&self, dest: &mut [u8]);

    /// Returns a pseudorandom `f64` value in the half-open interval `[0.0, 1.0)`.
    fn next_unit_f64(&self) -> f64;
}

/// A fast, deterministic 64-bit pseudorandom number generator using SplitMix64
/// with atomic state transitions (`AtomicU64`).
///
/// Intended strictly for non-cryptographic usage (tests, jitter, simulation).
/// Does NOT implement [`EntropyRng`] to prevent test PRNGs from entering cryptographic key paths.
#[derive(Debug)]
pub struct SeededRng {
    state: AtomicU64,
}

const GOLDEN_RATIO_64: u64 = 0x9e37_79b9_7f4a_7c15;

impl SeededRng {
    /// Creates a new [`SeededRng`] initialized with the given seed.
    pub fn new(seed: u64) -> Self {
        Self {
            state: AtomicU64::new(seed),
        }
    }

    /// Creates a new [`SeededRng`] seeded from process/runtime entropy.
    #[allow(clippy::disallowed_methods)]
    pub fn from_entropy() -> Self {
        let counter = ENTROPY_COUNTER.fetch_add(1, Ordering::Relaxed);

        let mut hasher1 = RandomState::new().build_hasher();
        hasher1.write_u64(counter);
        let h1 = hasher1.finish();

        let mut hasher2 = RandomState::new().build_hasher();
        hasher2.write_u64(h1);
        let h2 = hasher2.finish();

        let seed = h1 ^ h2.rotate_left(32) ^ GOLDEN_RATIO_64.wrapping_mul(counter);
        Self::new(seed)
    }
}

impl Rng for SeededRng {
    fn next_u64(&self) -> u64 {
        let z = self
            .state
            .fetch_add(GOLDEN_RATIO_64, Ordering::SeqCst)
            .wrapping_add(GOLDEN_RATIO_64);
        let mut z = z;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    fn fill_bytes(&self, mut dest: &mut [u8]) {
        while !dest.is_empty() {
            let val = self.next_u64();
            let bytes = val.to_le_bytes();
            let len = dest.len().min(8);
            dest[..len].copy_from_slice(&bytes[..len]);
            dest = &mut dest[len..];
        }
    }

    fn next_unit_f64(&self) -> f64 {
        let mantissa = self.next_u64() >> 11;
        (mantissa as f64) * (1.0 / (1u64 << 53) as f64)
    }
}

impl<T: EntropyRng + ?Sized> EntropyRng for Arc<T> {
    fn fill_bytes(&self, dest: &mut [u8]) {
        (**self).fill_bytes(dest);
    }

    fn next_u64(&self) -> u64 {
        (**self).next_u64()
    }
}

impl<T: Rng + ?Sized> Rng for Arc<T> {
    fn next_u64(&self) -> u64 {
        (**self).next_u64()
    }

    fn fill_bytes(&self, dest: &mut [u8]) {
        (**self).fill_bytes(dest);
    }

    fn next_unit_f64(&self) -> f64 {
        (**self).next_unit_f64()
    }
}

/// Standard production non-cryptographic [`Rng`] implementation seeded from process/runtime entropy.
#[derive(Debug)]
pub struct SystemRng {
    inner: SeededRng,
}

impl SystemRng {
    /// Creates a new [`SystemRng`].
    pub fn new() -> Self {
        Self {
            inner: SeededRng::from_entropy(),
        }
    }
}

impl Default for SystemRng {
    fn default() -> Self {
        Self::new()
    }
}

impl Rng for SystemRng {
    fn next_u64(&self) -> u64 {
        self.inner.next_u64()
    }

    fn fill_bytes(&self, dest: &mut [u8]) {
        self.inner.fill_bytes(dest);
    }

    fn next_unit_f64(&self) -> f64 {
        self.inner.next_unit_f64()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct MockEntropyRng;
    impl EntropyRng for MockEntropyRng {
        fn fill_bytes(&self, dest: &mut [u8]) {
            dest.fill(0xAA);
        }
        fn next_u64(&self) -> u64 {
            0x1234_5678_9ABC_DEF0
        }
    }

    fn assert_dyn_entropy(_: Option<&dyn EntropyRng>) {}
    fn assert_dyn_rng(_: Option<&dyn Rng>) {}

    #[test]
    fn test_rng_object_safety_and_type_separation() {
        let entropy_rng = Arc::new(MockEntropyRng);
        let seeded_rng = Arc::new(SeededRng::new(42));

        assert_dyn_entropy(Some(entropy_rng.as_ref()));
        assert_dyn_rng(Some(seeded_rng.as_ref()));

        let dyn_entropy: Arc<dyn EntropyRng> = entropy_rng;
        let mut buf = [0u8; 4];
        dyn_entropy.fill_bytes(&mut buf);
        assert_eq!(buf, [0xAA; 4]);

        let dyn_rng: Arc<dyn Rng> = seeded_rng;
        assert!(dyn_rng.next_u64() > 0);
        let f = dyn_rng.next_unit_f64();
        assert!((0.0..1.0).contains(&f));
    }

    fn crypto_key_gen<R: EntropyRng>(rng: &R, out: &mut [u8; 32]) {
        rng.fill_bytes(out);
    }

    #[test]
    fn test_entropy_rng_accepted_for_keys() {
        let rng = MockEntropyRng;
        let mut key = [0u8; 32];
        crypto_key_gen(&rng, &mut key);
        assert_eq!(key, [0xAA; 32]);
    }
}
